-- Flujo de revisión y publicación de casos (CRP-01).
--
-- Iván escribe borradores y los envía a revisión; el revisor aprueba,
-- devuelve o despublica. La web pública sólo lee `cases`.
--
-- La clave pública viaja dentro de la app, así que la seguridad vive aquí:
-- privilegios mínimos por rol + RLS + funciones `security definer` para
-- todos los cambios de estado. Nadie cambia un estado escribiendo la columna.

-- ------------------------------------------------------------------ revisores
create table public.reviewers (
  user_id uuid primary key references auth.users (id) on delete cascade
);

alter table public.reviewers enable row level security;
revoke all on public.reviewers from anon, authenticated;

-- Consultable desde las políticas sin exponer la tabla.
create function public.is_reviewer()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.reviewers where user_id = (select auth.uid())
  );
$$;

revoke execute on function public.is_reviewer() from public, anon;
grant execute on function public.is_reviewer() to authenticated;

-- --------------------------------------------------------- casos publicados
create table public.cases (
  slug text primary key
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  -- El objeto del caso tal cual lo lee la app, sin pasar por el modelo
  -- tipado: un viaje de ida y vuelta por el modelo pierde datos.
  payload jsonb not null
    check (jsonb_typeof(payload) = 'object' and payload ->> 'slug' = slug),
  -- Orden estable del catálogo: una sustitución conserva su posición.
  sort_order bigint generated by default as identity,
  published_at timestamptz not null default now(),
  published_by uuid references auth.users (id) on delete set null,
  -- Borrador del que salió; null en los casos cargados desde cases.json.
  source_draft_id text
);

alter table public.cases enable row level security;
revoke all on public.cases from anon, authenticated;
grant select on public.cases to anon, authenticated;

create policy "casos publicados visibles para todos"
  on public.cases for select
  to anon, authenticated
  using (true);

-- ---------------------------------------------------------------- borradores
create type public.draft_status as enum ('draft', 'in_review', 'returned', 'published');

create table public.drafts (
  -- Conserva el `draftId` que ya generan los navegadores.
  id text primary key
    check (char_length(id) between 1 and 100),
  owner uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  payload jsonb not null
    check (jsonb_typeof(payload) = 'object' and octet_length(payload::text) <= 500000),
  status public.draft_status not null default 'draft',
  published_slug text,
  submitted_at timestamptz,
  updated_at timestamptz not null default now()
);

create index drafts_owner_idx on public.drafts (owner);
create index drafts_status_idx on public.drafts (status);

alter table public.drafts enable row level security;
revoke all on public.drafts from anon, authenticated;
-- Iván sólo escribe el contenido y, al editar, el paso a draft/returned.
grant select, delete on public.drafts to authenticated;
grant insert (id, payload) on public.drafts to authenticated;
grant update (payload, status) on public.drafts to authenticated;

create policy "cada autor ve sus borradores; el revisor ve todos"
  on public.drafts for select
  to authenticated
  using (owner = (select auth.uid()) or (select public.is_reviewer()));

create policy "cada autor crea sus borradores"
  on public.drafts for insert
  to authenticated
  with check (owner = (select auth.uid()) and status = 'draft');

-- Mientras está en revisión el borrador queda congelado. Editar uno
-- publicado obliga a devolverlo a draft: la versión publicada no cambia
-- hasta que se apruebe la nueva.
create policy "cada autor edita sus borradores fuera de revisión"
  on public.drafts for update
  to authenticated
  using (owner = (select auth.uid()) and status <> 'in_review')
  with check (owner = (select auth.uid()) and status in ('draft', 'returned'));

create policy "cada autor borra sus borradores fuera de revisión"
  on public.drafts for delete
  to authenticated
  using (owner = (select auth.uid()) and status <> 'in_review');

create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger drafts_touch_updated_at
  before update on public.drafts
  for each row execute function public.touch_updated_at();

-- ------------------------------------------------------- cambios de estado
create function public.submit_draft(p_draft_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_owner uuid;
  v_status public.draft_status;
begin
  select owner, status into v_owner, v_status
  from public.drafts where id = p_draft_id
  for update;

  if v_owner is null or v_owner <> (select auth.uid()) then
    raise exception 'draft % not found for this user', p_draft_id
      using errcode = '42501';
  end if;
  if v_status not in ('draft', 'returned') then
    raise exception 'draft % is % and cannot be submitted', p_draft_id, v_status
      using errcode = '55000';
  end if;

  update public.drafts
  set status = 'in_review', submitted_at = now()
  where id = p_draft_id;
end;
$$;

create function public.return_draft(p_draft_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_reviewer() then
    raise exception 'only reviewers can return drafts' using errcode = '42501';
  end if;

  update public.drafts
  set status = 'returned'
  where id = p_draft_id and status = 'in_review';

  if not found then
    raise exception 'draft % is not in review', p_draft_id using errcode = '55000';
  end if;
end;
$$;

-- `p_case` es el objeto ya convertido por la app (`draftToCaseJson`), el
-- mismo que el revisor acaba de previsualizar.
create function public.approve_draft(p_draft_id text, p_case jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_draft public.drafts%rowtype;
  v_slug text := p_case ->> 'slug';
begin
  if not public.is_reviewer() then
    raise exception 'only reviewers can approve drafts' using errcode = '42501';
  end if;

  select * into v_draft from public.drafts where id = p_draft_id for update;
  if not found or v_draft.status <> 'in_review' then
    raise exception 'draft % is not in review', p_draft_id using errcode = '55000';
  end if;

  if v_slug is null or v_slug = '' then
    raise exception 'case payload has no slug' using errcode = '22023';
  end if;
  -- Una edición sustituye a su propio caso, nunca abre otro.
  if v_draft.published_slug is not null and v_draft.published_slug <> v_slug then
    raise exception 'draft % is published as %, not %',
      p_draft_id, v_draft.published_slug, v_slug
      using errcode = '22023';
  end if;

  -- Comprobar y escribir en una sola sentencia: el `where` del upsert se
  -- evalúa con la fila bloqueada, así dos aprobaciones simultáneas del mismo
  -- slug nuevo no se pisan. Nunca se sustituye un caso de otro borrador.
  insert into public.cases (slug, payload, published_at, published_by, source_draft_id)
  values (v_slug, p_case, now(), (select auth.uid()), p_draft_id)
  on conflict (slug) do update
  set payload = excluded.payload,
      published_at = excluded.published_at,
      published_by = excluded.published_by,
      source_draft_id = excluded.source_draft_id
  where public.cases.source_draft_id is null
     or public.cases.source_draft_id = excluded.source_draft_id;

  if not found then
    raise exception 'slug % belongs to another draft', v_slug using errcode = '55000';
  end if;

  update public.drafts
  set status = 'published', published_slug = v_slug
  where id = p_draft_id;
end;
$$;

create function public.unpublish_case(p_slug text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_reviewer() then
    raise exception 'only reviewers can unpublish cases' using errcode = '42501';
  end if;

  delete from public.cases where slug = p_slug;
  if not found then
    raise exception 'case % is not published', p_slug using errcode = 'P0002';
  end if;

  update public.drafts
  set status = 'draft', published_slug = null
  where published_slug = p_slug;
end;
$$;

revoke execute on function
  public.submit_draft(text),
  public.return_draft(text),
  public.approve_draft(text, jsonb),
  public.unpublish_case(text)
from public, anon;

grant execute on function
  public.submit_draft(text),
  public.return_draft(text),
  public.approve_draft(text, jsonb),
  public.unpublish_case(text)
to authenticated;
